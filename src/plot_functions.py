def area_weighted_mean(da):
    """
    Compute global mean weighted by latitude area
    da(lat, lon, leadtime)
    """

    lat = da.lat

    weights = np.cos(np.deg2rad(lat))

    weights = xr.DataArray(
        weights,
        coords={"lat": lat},
        dims=["lat"]
    )

    return (
        da.weighted(weights)
        .mean(dim=("lat", "lon"))
    )


