def compute_and_plot_histograms(results,
                                dir_plot,
                                config,
                                log,
                                size_box=2,
                                days=[1, 3, 5]):

    """
        Compute and plot histograms of Lagrangian validation diagnostics.

        This function extracts separation distance and Liu skill score values
        from the outputs of ``process_one_day()`` over the selected validation
        period, aggregates the results, and generates histogram plots for
        specified lead times.

        Histograms are used to evaluate the distribution of trajectory errors
        and skill scores across all drifters and forecast periods.

        Parameters
        ----------
        results : list of dict
            List of outputs returned by ``process_one_day()``. Each dictionary
            is expected to contain daily Lagrangian diagnostics such as
            separation distance and Liu skill score.

        dir_plot : str
            Directory where histogram figures will be saved.

        MODEL : str
            Name of the ocean model or forecasting system being evaluated.
            Used in figure titles and output filenames.

        DATE_START : str
            Start date of the validation period (typically YYYYMMDD).

        DATE_END : str
            End date of the validation period (typically YYYYMMDD).

        size_box : int, optional
            Spatial bin size (degrees) used during the gridding process.
            Included in output figure metadata and filenames.
            Default is 2.

        days : list of int, optional
            Lead times (in days) for which histograms are generated.
            Default is [1, 3, 5].

        Notes
        -----
        The function computes histograms for:

        - Separation distance (km):
          Distance between observed and simulated drifter positions.

        - Liu skill score:
          Trajectory skill metric ranging from 0 to 1 (values above 1 may
          occur depending on the implementation and normalization).

        Histograms are generated using all available trajectories from the
        selected period and can optionally be restricted to a given range
        (e.g. separation distance < 125 km or Liu score < 1.2) to improve
        visualization of the most populated part of the distributions.

        Outputs
        -------
        PNG files containing histograms of separation distance and Liu skill
        score for each requested lead time, saved in ``dir_plot``.
    """

    MODEL = config['SYSTEM']
    DATE_START = config['DATE_START']
    DATE_END = config['DATE_END']
    scheme = config['scheme']
    sampling = config["parcels_dt_minutes"]

    # ==========================================================
    # Collect data
    # ==========================================================

    all_sep_daily = []
    all_liu_daily = []

    for res in results:
        if res is None:
            continue

        if "sep_dist_daily" in res:
            all_sep_daily.append(np.asarray(res["sep_dist_daily"]).reshape(-1, np.asarray(res["sep_dist_daily"]).shape[-1]))

        if "liu_skill_daily" in res:
            all_liu_daily.append(np.asarray(res["liu_skill_daily"]).reshape(-1, np.asarray(res["liu_skill_daily"]).shape[-1]))

    all_sep_daily = np.concatenate(all_sep_daily, axis=0)
    all_liu_daily = np.concatenate(all_liu_daily, axis=0)

    log.debug(f"sep shape: {all_sep_daily.shape}")
    log.debug(f"liu shape: {all_liu_daily.shape}")
    log.debug(all_liu_daily)
    # ==========================================================
    # Output file
    # ==========================================================

    fig_out = (
        dir_plot
        + '/Hist_stats_'
        + MODEL + '_'
        + str(DATE_START)
        + '_' + str(DATE_END)
        + '_' + str(scheme)
        + '_' + str(sampling)
        + '.png'
    )

    # ==========================================================
    # Figure (matplotlib)
    # ==========================================================

    fig, axs = plt.subplots(1, 2, figsize=(9, 5))

    fig.suptitle(f"{MODEL}, {DATE_START}-{DATE_END}", fontsize=14)

    lead_colors = {
        1: "red", 3: "blue", 5: "green", 7: "black", 9: "yellow",
        12: "purple", 15: "cyan", 20: "magenta", 28: "orange",
    }
    fallback_colors = plt.cm.tab10(np.linspace(0, 1, max(len(days), 1)))

    # ==========================================================
    # Separation distance histogram
    # ==========================================================

    ax = axs[0]
    bin_dict = {}
    bin_dict[0] = 1
    bin_dict[1] = 2
    bin_dict[2] = 2
    bin_dict[3] = 5
    bin_dict[4] = 5
    bin_dict[5] = 5
    bin_dict[6] = 5
    bin_dict[7] = 10
    bin_dict[8] = 10
    bin_dict[9] = 10


    for i, day in enumerate(days):
        bins = np.arange(0, 201, 5)

        idx = day - 1
        if idx >= all_sep_daily.shape[1]:
            continue

        dist = all_sep_daily[:, idx]
        dist = dist[np.isfinite(dist)]

        if len(dist) == 0:
            log.warning("No finite separation-distance samples for lead day %d", day)
            continue

        counts, _ = np.histogram(dist, bins=bins)
        freq = counts / len(dist)

        bin_centres = bins[:-1] + (bins[1] - bins[0]) / 2
        ax.plot(bin_centres, freq, lw=2, color=lead_colors.get(day, fallback_colors[i]), label=f"{day} day")

    ax.set_xlabel(f"Separation distance [km] {scheme} dt:{sampling}")
    ax.set_ylabel("Frequency")
    ax.set_xlim(0, 200)
    ax.set_ylim(0, 0.15)
    ax.grid(True, which="major", axis="both", alpha=0.3,linestyle="--")
    ax.legend()

    # ==========================================================
    # Liu score histogram
    # ==========================================================

    ax = axs[1]


    bin_dict2 = {}
    bin_dict2[0] = 0.1 #0.01
    bin_dict2[1] = 0.1 #0.02
    bin_dict2[2] = 0.1 #0.02
    bin_dict2[3] = 0.1 #0.05
    bin_dict2[4] = 0.1 #0.05
    bin_dict2[5] = 0.1 #0.05
    bin_dict2[6] = 0.1 #0.05
    bin_dict2[7] = 0.1 #0.1
    bin_dict2[8] = 0.1 #0.1
    bin_dict2[9] = 0.1 #0.1
    for i, day in enumerate(days):

        #bins2 = np.arange(0, 3, 0.1)
        bins2 = np.arange(0, 3.1, 0.1)
        bin_centres2 = bins2[:-1] + (bins2[1] - bins2[0]) / 2
        idx = day - 1
        if idx >= all_liu_daily.shape[1]:
            continue

        liu = all_liu_daily[:, idx]
        liu = liu[np.isfinite(liu)]

        if len(liu) == 0:
            log.warning("No finite Liu samples for lead day %d", day)
            continue

        counts, _ = np.histogram(liu, bins=bins2)
        freq = counts / len(liu)

        ax.plot(bin_centres2, freq, lw=2, color=lead_colors.get(day, fallback_colors[i]), label=f"{day} day")

    ax.set_xlabel("Liu index")
    ax.set_ylabel("Frequency")
    ax.set_xlim(0, 3)
    ax.set_ylim(0, 0.20)
    ax.grid(True, which="major", axis="both", alpha=0.3,linestyle="--")
    ax.legend()

    # ==========================================================
    # Save
    # ==========================================================

    plt.tight_layout()
    plt.savefig(fig_out, dpi=300)
    plt.close()

    log.info(f"Saved: {fig_out}")
    if config.get("SYSTEM", "").upper() != "GLOENS":
        plot_liu_diagnostics(results, dir_plot, config, log, list_days=days)


def plot_liu_diagnostics(results, dir_plot, config, log,
                         list_days=(1, 3, 5, 10)):
    """Plot lead-day Liu components and valid/clipped trajectory counts.

    Uses per-trajectory outputs, not gridded means, to avoid concealing
    sample-population changes or the unbounded pre-clipping error ratio.
    """
    from pathlib import Path

    keys = (
        ("normalized_error", "Raw normalized error", "Ratio"),
        ("observed_path_km", "Observed path length", "km"),
        ("normalization_distance_km", "Liu denominator", "km"),
        ("cumulative_separation_km", "Cumulative separation", "km"),
        ("instantaneous_separation_km", "Endpoint separation", "km"),
    )
    records = [r["liu_diagnostics_daily"] for r in results
               if r is not None and "liu_diagnostics_daily" in r]
    if not records:
        log.warning("No Liu diagnostics available; skipping diagnostic plots")
        return

    def matrix(record, key):
        values = np.asarray(record[key], dtype=float)
        if values.ndim == 1:
            values = values[np.newaxis, :]
        if values.ndim != 2:
            raise ValueError(f"Expected 2D drifter-by-lead {key}; got {values.shape}")
        return values

    available = min(matrix(r, keys[0][0]).shape[1] for r in records)
    days = [day for day in list_days if 1 <= day <= available]
    if not days:
        log.warning("No requested Liu diagnostic lead days in 1..%d", available)
        return
    positions = np.arange(len(days))
    fig, axes = plt.subplots(3, 2, figsize=(13, 13))
    for ax, (key, label, unit) in zip(axes.flat[:5], keys):
        samples = []
        for day in days:
            data = np.concatenate([matrix(r, key)[:, day - 1] for r in records])
            samples.append(data[np.isfinite(data)])
        ax.boxplot([x if x.size else np.array([np.nan]) for x in samples],
                   positions=positions, showfliers=False)
        ax.set_xticks(positions, [str(day) for day in days])
        ax.set_title(label)
        ax.set_xlabel("Forecast lead (days)")
        ax.set_ylabel(unit)
        ax.grid(axis="y", alpha=0.25)
    ax = axes.flat[5]
    valid_counts, clipped_counts = [], []
    for day in days:
        raw = np.concatenate([matrix(r, "normalized_error")[:, day - 1]
                              for r in records])
        finite = raw[np.isfinite(raw)]
        valid_counts.append(finite.size)
        clipped_counts.append(np.count_nonzero(finite >= 1.0))
    ax.bar(positions, valid_counts, label="Valid trajectories", alpha=0.8)
    ax.bar(positions, clipped_counts, label="Clipped to zero", alpha=0.8)
    ax.set_xticks(positions, [str(day) for day in days])
    ax.set_title("Trajectory sample counts")
    ax.set_xlabel("Forecast lead (days)")
    ax.set_ylabel("Count")
    ax.legend()
    ax.grid(axis="y", alpha=0.25)
    fig.suptitle("Liu skill diagnostics: " + str(config.get("SYSTEM", "")))
    fig.tight_layout()
    output = Path(dir_plot) / (
        "Liu_diagnostics_" + str(config.get("SYSTEM", "model")) + "_"
        + str(config.get("DATE_START", "")) + "_"
        + str(config.get("DATE_END", "")) + ".png"
    )
    fig.savefig(output, dpi=250)
    plt.close(fig)
    log.info("Saved Liu diagnostics: %s", output)



def plot_extended_trajectory_diagnostics(results, dir_plot, config, log,
                                         lead_groups=((1, 3, 5, 10), (12, 15, 20, 28)),
                                         grid_degrees=2, min_count=10):
    """Paired-trajectory distributions and observed-position geographic diagnostics.

    Speed is mean observed drifter speed since initialization. Daily angular
    error compares paired daily displacement vectors. All missing values are
    excluded pairwise; sparse geographic bins are masked.
    """
    from pathlib import Path
    records = [r["liu_diagnostics_daily"] for r in results
               if r is not None and "liu_diagnostics_daily" in r]
    if not records:
        log.warning("No extended trajectory diagnostics available")
        return

    def matrix(record, key):
        values = np.asarray(record[key], dtype=float)
        if values.ndim == 1:
            values = values[np.newaxis, :]
        if values.ndim != 2:
            raise ValueError(f"Expected drifter-by-lead {key}, got {values.shape}")
        return values

    def samples(key, day):
        arrays = [matrix(r, key)[:, day - 1] for r in records
                  if key in r and matrix(r, key).shape[1] >= day]
        return np.concatenate(arrays) if arrays else np.array([])

    # Do not let a short cycle suppress later leads from longer cycles.
    available = max(matrix(r, "normalized_error").shape[1] for r in records)
    log.info("Extended diagnostics: maximum available lead day %d", available)
    out = Path(dir_plot)
    out.mkdir(parents=True, exist_ok=True)
    system = str(config.get("SYSTEM", "model"))
    stamp = f"{system}_{config.get('DATE_START', '')}_{config.get('DATE_END', '')}"
    speed_edges = np.array([0, .3, .6, 1., 1.5, 2., np.inf])
    speed_labels = ["0–0.3", "0.3–0.6", "0.6–1", "1–1.5", "1.5–2", "≥2"]
    # Performance and observation diagnostics share one figure each, with all
    # requested lead days; geographical maps remain in four-panel groups.
    combined_days = list(dict.fromkeys(day for group in lead_groups for day in group))
    for requested in (combined_days,):
        days = [day for day in requested if 1 <= day <= available]
        if not days:
            continue
        tag = "_".join(map(str, days))
        metrics = [
            ("observed_path_km", "Observed path length", "km"),
            ("model_path_km", "Model path length", "km"),
            ("normalized_error", "Normalized error", "ratio"),
            ("instantaneous_separation_km", "Separation distance", "km"),
            ("directional_error_deg", "Daily directional error", "degrees"),
            ("skill", "Liu skill score", "score"),
        ]
        fig, axes = plt.subplots(3, 2, figsize=(13, 13))
        for ax, (key, title, unit) in zip(axes.flat, metrics):
            values = [v[np.isfinite(v)] for day in days
                      for v in [samples(key, day)]]
            ax.boxplot([v if v.size else [np.nan] for v in values],
                       tick_labels=[str(d) for d in days], showfliers=False)
            ax.set(title=title, xlabel="Forecast lead (days)", ylabel=unit)
            ax.grid(axis="y", alpha=.25)
        fig.suptitle(f"Trajectory performance: {system} (days {tag})")
        fig.tight_layout()
        path = out / f"Trajectory_performance_{stamp}_days{tag}.png"
        fig.savefig(path, dpi=200)
        plt.close(fig)
        log.info("Saved %s", path)

        fig, axes = plt.subplots(3, 2, figsize=(15, 13))
        # Observation-focused panels: speed distribution, separation by
        # speed, angle by speed, normalized error by speed, pair counts,
        # and original Liu valid/zero-clipped sample counts.
        ax = axes.flat[0]
        speed_arrays = [samples("observed_speed_ms", day) for day in days]
